import { chromium } from 'playwright-core';

const results = [];
const check = (name, ok, info = '') => { results.push(!!ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${info ? '  ' + info : ''}`); };
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
const errors = [], external = [], sent = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { const tx = m.text(), mm = /sendMessage\(\)\s.*\s(\w+)$/.exec(tx); if (mm) sent.push(mm[1]); if (m.type() === 'error' && !/Failed to load resource/.test(tx)) errors.push(tx); });
page.on('request', (r) => { const u = r.url(); if (!u.startsWith('http://localhost:8765/') && !u.startsWith('data:') && !u.startsWith('blob:')) external.push(u); });
await page.goto('http://localhost:8765/Backrooms%20FPS%20Playgama/index.html?debug&menu=1');
await page.waitForFunction(() => { const b = document.getElementById('boot-enter'); return b && !b.classList.contains('hidden'); }, null, { timeout: 120000 });
const boot = await page.evaluate(() => ({ init: !!(window.bridge && window.bridge.isInitialized), platform: window.bridge && window.bridge.platform.id, ready: window.__BR.Platform.sdkReady }));
check('Bridge SDK initializes', boot.init && boot.ready, JSON.stringify(boot));
check('game_ready is sent once loading is done', sent.includes('game_ready'), sent.join(','));
await page.click('#boot-enter');
await page.waitForFunction(() => window.__BR.Ui.cur === 'menu', null, { timeout: 30000 });
await page.evaluate(() => { const B = window.__BR, m = B.MISSIONS[0]; B.Game.start(0, m.primary, m.secondary); });
await page.waitForFunction(() => window.__BR.Game.state === 'play' && !window.__BR.Game.starting, null, { timeout: 90000 });
await page.evaluate(() => { const G = window.__BR.Game; G.countdownT = 0; for (let k = 0; k < 120; k++) G.update(1 / 30); });
const play = await page.evaluate(() => ({ actors: window.__BR.Game.actors.length }));
check('Mission 1 starts and plays', play.actors > 1, JSON.stringify(play));
check('gameplay_started is sent in a match', sent.includes('gameplay_started'), sent.join(','));
const ads = await page.evaluate(async () => {
  const P = window.__BR.Platform, t0 = performance.now();
  await Promise.race([P.ads.midgame(), new Promise((r) => setTimeout(r, 35000))]);
  const inter = performance.now() - t0;
  const rw = await Promise.race([P.ads.rewarded(), new Promise((r) => setTimeout(() => r('timeout'), 35000))]);
  return { inter: Math.round(inter), rw, state: window.bridge.advertisement.interstitialState, sup: [window.bridge.advertisement.isInterstitialSupported, window.bridge.advertisement.isRewardedSupported] };
});
check('Interstitial call resolves and the game continues', ads.inter < 35000, JSON.stringify(ads));
check('Rewarded call resolves to a boolean', typeof ads.rw === 'boolean', String(ads.rw));
const sim = await page.evaluate(async () => {
  const ad = window.bridge.advertisement, hs = {};
  for (const k of ['isInterstitialSupported', 'isRewardedSupported']) Object.defineProperty(ad, k, { get: () => true, configurable: true });
  ad.on = (ev, cb) => { (hs[ev] = hs[ev] || []).push(cb); };
  ad.off = (ev, cb) => { hs[ev] = (hs[ev] || []).filter((f) => f !== cb); };
  const play = (ev, states) => states.forEach((st, i) => setTimeout(() => (hs[ev] || []).slice().forEach((f) => f(st)), 80 * (i + 1)));
  ad.showInterstitial = () => play('interstitial_state_changed', ['loading', 'opened', 'closed']);
  ad.showRewarded = () => play('rewarded_state_changed', ['loading', 'opened', 'rewarded', 'closed']);
  const B = window.__BR, P = B.Platform;
  B.Platform.gameplayStart();
  let pausedDuring = null;
  const iv = setInterval(() => { if (pausedDuring === null && document.querySelector('.ad-veil, #ad-veil')) pausedDuring = true; }, 10);
  await P.ads.midgame();
  const rw = await P.ads.rewarded();
  clearInterval(iv);
  return { rw, listeners: Object.values(hs).reduce((n, l) => n + l.length, 0) };
});
check('Simulated interstitial and rewarded ads complete, reward granted', sim.rw === true && sim.listeners === 0, JSON.stringify(sim));
check('gameplay_stopped is sent around an ad', sent.includes('gameplay_stopped'), sent.join(','));
const save = await page.evaluate(async () => {
  const P = window.__BR.Platform;
  await P.saveData('{"probe":1}');
  const back = await P.loadData();
  return back;
});
check('Save round-trip through bridge.storage', save === '{"probe":1}', save);
await page.evaluate(async () => window.__BR.Save.persist && window.__BR.Save.persist(true));
check('No requests outside the game folder', !external.length, external.slice(0, 3).join(' '));
check('No errors', !errors.length, errors.slice(0, 3).join(' | '));
await browser.close();
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
process.exit(results.every(Boolean) ? 0 : 1);
