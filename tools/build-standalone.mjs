// Generates "Backrooms FPS Standalone/" from the YouTube Playables build in "Backrooms FPS/".
// The standalone copy has every YouTube Playables integration removed (no SDK <script>, no ytgame calls):
// progress is saved in the browser (localStorage) and the language follows the browser.
// Rerun after any change to the game:  cd tools && npm run standalone
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../Backrooms FPS');
const out = path.resolve(here, '../Backrooms FPS Standalone');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

for (const item of ['css', 'lib', 'assets', 'LICENSES.txt']) fs.cpSync(path.join(src, item), path.join(out, item), { recursive: true });

// index.html: drop the SDK tag and its comment.
let html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
html = html.replace(/\s*<!-- YouTube Playables SDK[^>]*-->\s*<script src="https:\/\/www\.youtube\.com\/game_api\/v1"><\/script>/, '');
fs.writeFileSync(path.join(out, 'index.html'), html);

// game.js: swap the Playables platform layer for a local one.
let js = fs.readFileSync(path.join(src, 'game.js'), 'utf8');
const replaceBetween = (startMark, endMark, text) => {
  const a = js.indexOf(startMark), b = js.indexOf(endMark, a);
  if (a < 0 || b < 0) throw new Error('marker not found: ' + startMark);
  js = js.slice(0, a) + text + js.slice(b);
};
const sub = (from, to) => { if (!js.includes(from)) throw new Error('text not found: ' + from); js = js.split(from).join(to); };

sub('BACKROOMS — Tactical FPS for YouTube Playables', 'BACKROOMS — Tactical FPS (standalone build, no YouTube Playables integration)');
sub('   No network access besides the YouTube Playables SDK tag in index.html.', '   No network access at all. Generated by tools/build-standalone.mjs from "Backrooms FPS/game.js".');
sub('   2. LOCALIZATION (ytgame.system.getLanguage)', '   2. LOCALIZATION (browser language)');
sub('   20. MAIN LOOP — stops completely while paused (YouTube onPause)', '   20. MAIN LOOP — stops completely while paused (tab hidden)');
sub('   4. SAVE DATA — progress, best scores, settings (ytgame.game.saveData)', '   4. SAVE DATA — progress, best scores, settings (localStorage)');
replaceBetween('/* ---------------------------------------------------------------------------\n   3. PLATFORM', '/* ---------------------------------------------------------------------------\n   4. SAVE DATA', `/* ---------------------------------------------------------------------------
   3. PLATFORM — standalone: browser storage and language, nothing else
   --------------------------------------------------------------------------- */
const Platform = (() => {
  const safe = (fn, fallback) => { try { return fn(); } catch (e) { return fallback; } };
  const noop = () => {};
  const api = {
    inPlayables: false,
    firstFrameReady: noop, gameReady: noop, sendScore: noop, logError: noop, logWarning: noop, onAudioEnabledChange: noop,
    async getLanguage() { return String(navigator.language || 'en').toLowerCase().slice(0, 2); },
    isAudioEnabled() { return true; },
    onPause(cb) { document.addEventListener('visibilitychange', () => { if (document.hidden) cb(); }); },
    onResume(cb) { document.addEventListener('visibilitychange', () => { if (!document.hidden) cb(); }); },
    async loadData() { return safe(() => localStorage.getItem('backrooms.save') || '', ''); },
    async saveData(str) { safe(() => localStorage.setItem('backrooms.save', str)); },
  };
  window.addEventListener('error', (e) => console.error('[backrooms]', e.message));
  window.addEventListener('unhandledrejection', (e) => console.error('[backrooms]', e.reason));
  return api;
})();

`);
// Optional base64 assets for hosts that won't serve .glb files (set by tools/build-web-demo.mjs only).
sub(`  async binary(url, kb) {
    const r = await fetch(url);`, `  async binary(url, kb) {
    if (window.BACKROOMS_WEB_DEMO && window.BACKROOMS_WEB_DEMO.b64) {
      const r = await fetch(url + '.b64.txt');
      if (!r.ok) throw new Error('Failed to load ' + url);
      const bin = atob((await r.text()).trim()); const out = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
      this.bump(kb); return out.buffer;
    }
    const r = await fetch(url);`);
fs.writeFileSync(path.join(out, 'game.js'), js);

const left = (html + js).match(/ytgame|youtube\.com|game_api/gi);
if (left) throw new Error('YouTube references left in standalone build: ' + [...new Set(left)].join(', '));
console.log('wrote', path.relative(path.resolve(here, '..'), out));
