import { chromium } from 'playwright-core';
const url = process.argv[2] || 'http://localhost:8766/dev/index.html?net=off';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 960, height: 540 } })).newPage();
const errors = [], results = [];
page.on('pageerror', (e) => errors.push(e.message));
const check = (name, ok, info = '') => { results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${info}`); };
const ev = (f, a) => page.evaluate(f, a);
await page.goto(url);
await page.waitForFunction(() => window.__vi && window.__vi.ui);
await ev(() => window.__vi.startLobby('deathrun', { fast: true, countdown: 0, firstWait: 0 }));
await page.waitForFunction(() => window.__vi.m && window.__vi.m.state === 'play', null, { timeout: 30000 });
const map = await ev(() => { const m = window.__vi.m; return { n: m.map.checkpoints.length, floor: m.map.checkpoints.every((c) => m.world.get(Math.floor(c.x), c.y - 1, 0) && [58, 0].includes(m.world.get(Math.floor(c.x), c.y, 0))) }; });
check('course has checkpoints on solid floor', map.n >= 5 && map.floor, JSON.stringify(map));
const ri = await ev(() => { const a = window.__vi, m = a.m; const o = a.me.role === 'runner' ? a.me : m.actors.find((x) => x.role === 'runner'); window.__r = o; return m.actors.indexOf(o); });
await ev(() => { const m = window.__vi.m, o = window.__r; m.kill(o, m.mode.death, 'trap'); });
const d1 = await ev(() => ({ alive: window.__r.alive, elim: window.__r.eliminated, t: window.__r.respawnT }));
check('runner not knocked out after dying', !d1.alive && !d1.elim && d1.t > 0, JSON.stringify(d1));
await page.waitForTimeout(2600);
const r1 = await ev(() => { const o = window.__r; return { alive: o.alive, x: o.pos.x, sx: o.start.x, st: window.__vi.state }; });
check('comes back at start when no checkpoint yet', r1.alive && Math.abs(r1.x - r1.sx) < 3 && r1.st === 'play', JSON.stringify(r1));
await ev(() => { const o = window.__r, c = window.__vi.m.map.checkpoints[1]; o.pos.x = c.x + 1; o.pos.y = c.y; o.pos.z = c.z; o.vel.x = o.vel.y = o.vel.z = 0; });
await page.waitForTimeout(400);
const cp = await ev(() => window.__r.cp);
check('checkpoint reached', cp >= 2, 'cp ' + cp);
await ev(() => { const o = window.__r; o.pos.y -= 40; });
await page.waitForTimeout(3600);
const r2 = await ev(() => { const o = window.__r, c = window.__vi.m.map.checkpoints[o.cp - 1]; return { alive: o.alive, d: Math.hypot(o.pos.x - c.x, o.pos.z - c.z), dy: o.pos.y - c.y, st: window.__vi.state, deaths: o.deaths }; });
check('void fall brings runner back to last checkpoint', r2.alive && r2.d < 2 && Math.abs(r2.dy) < 1.5 && r2.st === 'play' && r2.deaths === 2, JSON.stringify(r2));
const bot = await ev(() => { const m = window.__vi.m; const b = m.actors.find((x) => x.role === 'runner' && x.botRef && x !== window.__r && x.alive); window.__b = b; const c = m.map.checkpoints[2]; b.pos.x = c.x + 1; b.pos.y = c.y; b.pos.z = c.z; b.vel.x = b.vel.y = b.vel.z = 0; return !!b; });
await page.waitForTimeout(400);
await ev(() => { const m = window.__vi.m; m.kill(window.__b, m.mode.death, 'trap'); });
await page.waitForTimeout(2500);
const bx0 = await ev(() => ({ x: window.__b.pos.x, alive: window.__b.alive }));
await page.waitForTimeout(5000);
const bx1 = await ev(() => ({ x: window.__b.pos.x, alive: window.__b.alive }));
check('bot respawns and keeps running', bot && bx0.alive && bx1.x > bx0.x + 3, `${bx0.x.toFixed(1)} -> ${bx1.x.toFixed(1)}`);
await ev(() => window.__vi.toMenu('modes'));
await page.waitForTimeout(500);
const soon = await ev(() => [...document.querySelectorAll('.card.soon h2')].map((e) => e.textContent));
check('Zero Gravity coming-soon card', soon.includes('Zero Gravity'), soon.join(', '));
await page.screenshot({ path: new URL('./out/modes-zerog.png', import.meta.url).pathname });
check('no page errors', !errors.length, errors.join(' | '));
await browser.close();
const f = results.filter((r) => !r).length;
console.log(f ? `${f} FAILED` : 'ALL PASS');
process.exit(f ? 1 : 0);
