import { chromium } from 'playwright-core';
import fs from 'node:fs';
const url = process.argv[2] || 'http://localhost:8766/dev/index.html';
const mode = process.argv[3] || 'sky';
const [w, h] = (process.argv[4] || '1280x720').split('x').map(Number);
const touch = process.argv.includes('--touch');
const out = new URL('./out/', import.meta.url).pathname;
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: w, height: h }, hasTouch: touch, isMobile: touch })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + e.stack));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.type() + ': ' + m.text()); });
const tag = `${mode}-${w}x${h}${touch ? '-touch' : ''}`;
const shot = (n) => page.screenshot({ path: `${out}${tag}-${n}.png` });
await page.goto(url);
await page.waitForTimeout(2500);
await shot('1-menu');
await page.click('[data-act=modes]');
await page.waitForTimeout(500);
await shot('2-modes');
await page.click(`[data-act=mode][data-mode=${mode}]`);
await page.waitForTimeout(3500);
await shot('3-lobby');
await page.waitForFunction(() => window.__vi.state === 'play' && window.__vi.m, null, { timeout: 30000 });
await page.waitForTimeout(1500);
await shot('4-countdown');
await page.waitForFunction(() => window.__vi.m.state === 'play', null, { timeout: 15000 });
await page.waitForTimeout(800);
await shot('5-go');
const info = await page.evaluate(() => { const a = window.__vi; return { fps: a.pixel, actors: a.m.actors.map((x) => x.name + (x.bot ? '' : '*')), sel: a.me.sel, inv: a.me.inv.slots.filter(Boolean).map((s) => s.id + 'x' + s.count) }; });
console.log(JSON.stringify(info));
if (mode === 'sky') {
  await page.evaluate(() => { const a = window.__vi; const c = a.m.map.chests.find((c) => Math.hypot(c.x - a.me.pos.x, c.z - a.me.pos.z) < 8); a.openChest(c); });
  await page.waitForTimeout(400);
  await shot('6-chest');
  await page.click('[data-act=takeAll]');
  await page.waitForTimeout(300);
  await shot('7-chest-taken');
  await page.click('[data-act=closePanel]');
} else {
  await page.evaluate(() => { const a = window.__vi; a.me.inv.add(170, 40); a.me.inv.add(171, 10); a.openShop(); });
  await page.waitForTimeout(400);
  await shot('6-shop');
  await page.click('[data-act=buy][data-id=wool]');
  await page.click('[data-act=shopCat][data-c=armor]');
  await page.waitForTimeout(300);
  await shot('7-shop-armor');
  await page.click('[data-act=closePanel]');
}
await page.evaluate(() => { const a = window.__vi; a.me.yaw += Math.PI; a.me.pitch = -0.35; });
await page.waitForTimeout(600);
await shot('8-look');
await page.evaluate(() => { const a = window.__vi; const o = a.m.actors.find((x) => x !== a.me && x.alive); a.me.pos.x = o.pos.x + 2.5; a.me.pos.y = o.pos.y; a.me.pos.z = o.pos.z; a.me.yaw = Math.atan2(2.5, 0); a.me.pitch = -0.1; o.ctl = null; });
await page.waitForTimeout(700);
await shot('9-near-player');
await page.evaluate(() => { const a = window.__vi; a.m.kill(a.me, null, 'void'); });
await page.waitForTimeout(mode === 'sky' ? 3200 : 1500);
await shot('10-dead');
if (mode === 'sky') {
  const st = await page.evaluate(() => window.__vi.state);
  console.log('after death state', st);
  if (st === 'results') { await page.click('[data-act=spectate]'); await page.waitForTimeout(1500); await shot('11-spectate'); }
}
await page.evaluate(() => { const a = window.__vi; for (const o of a.m.actors) if (o !== a.m.actors[1] && o.alive) a.m.kill(o, a.m.actors[1], 'melee'); if (a.m.mode.id === 'egg') for (const t of a.m.mode.teams) a.m.mode.breakEgg(t, null); for (const o of a.m.actors) if (o.team !== a.m.actors[1].team && o.alive) a.m.kill(o, null, 'void'); });
await page.waitForTimeout(4500);
await shot('12-results');
console.log('final state', await page.evaluate(() => window.__vi.state), await page.evaluate(() => JSON.stringify(window.__vi.save.data)));
console.log(errors.length ? errors.slice(0, 8).join('\n') : 'no errors');
await browser.close();
