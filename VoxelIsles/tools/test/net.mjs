const watch = (p, idx, ms) => ev(p, ([idx, ms]) => new Promise((res) => { const a = window.__vi, o = a.m.actors[idx]; let last = { ...o.pos }, lt = performance.now(), maxStep = 0, total = 0, frames = 0; const t0 = lt; const f = () => { const n = performance.now(), d = Math.hypot(o.pos.x - last.x, o.pos.z - last.z); if (frames) maxStep = Math.max(maxStep, d / Math.max(0.016, (n - lt) / 1000) / 60); total += d; frames++; last = { ...o.pos }; lt = n; if (n - t0 < ms) requestAnimationFrame(f); else res({ maxStep, total, frames }); }; f(); }), [idx, ms]);
